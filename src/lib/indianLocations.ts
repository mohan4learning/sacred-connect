export const getCities = (): string[] => {
  return Object.keys(indianLocations).sort();
};

export const getAreasForCity = (city: string): string[] => {
  const normalizedCity = Object.keys(indianLocations).find(
    c => c.toLowerCase() === city.toLowerCase()
  );
  return normalizedCity ? indianLocations[normalizedCity].sort() : [];
};

export const searchCities = (query: string): string[] => {
  if (!query.trim()) return getCities().slice(0, 10);
  const lowerQuery = query.toLowerCase();
  return getCities().filter(city => 
    city.toLowerCase().includes(lowerQuery)
  );
};

export const searchAreas = (city: string, query: string): string[] => {
  const areas = getAreasForCity(city);
  if (!query.trim()) return areas.slice(0, 10);
  const lowerQuery = query.toLowerCase();
  return areas.filter(area => 
    area.toLowerCase().includes(lowerQuery)
  );
};
